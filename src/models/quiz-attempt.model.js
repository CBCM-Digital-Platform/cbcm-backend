module.exports = (sequelize, DataTypes) => sequelize.define('QuizAttempt', {
	id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true },
	quiz_id: { type: DataTypes.INTEGER, allowNull: false },
	mentee_id: { type: DataTypes.INTEGER, allowNull: false },
	attempt_number: { type: DataTypes.INTEGER, defaultValue: 1 },
	score: { type: DataTypes.FLOAT, defaultValue: 0 },
	passed: { type: DataTypes.BOOLEAN, defaultValue: false },
	status: { type: DataTypes.STRING, defaultValue: 'in_progress' },
	started_at: { type: DataTypes.DATE },
	attempted_at: { type: DataTypes.DATE },
	completed_at: { type: DataTypes.DATE },
	ended_at: { type: DataTypes.DATE },
	created_at: { type: DataTypes.DATE },
	updated_at: { type: DataTypes.DATE },
}, { tableName: 'quiz_attempts', timestamps: true, createdAt: 'created_at', updatedAt: 'updated_at' });
