for (const [sourceName, targetName, foreignKey, as, inverseAs, oneToOne] of foreignKeys) {
	const source = models[sourceName];
	const target = models[targetName];
	source.belongsTo(target, { foreignKey, as });
	if (oneToOne) {
		target.hasOne(source, { foreignKey, as: inverseAs });
	} else {
		target.hasMany(source, { foreignKey, as: inverseAs });
	}
}

