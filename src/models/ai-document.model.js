module.exports = (sequelize, DataTypes) => sequelize.define('AIDocument', {
	id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true },
	title: { type: DataTypes.STRING, allowNull: false },
	description: { type: DataTypes.TEXT },
	category: { type: DataTypes.STRING },
	language: { type: DataTypes.STRING, defaultValue: 'en' },
	source_organization: { type: DataTypes.STRING },
	document_version: { type: DataTypes.STRING },
	publication_date: { type: DataTypes.DATEONLY },
	review_date: { type: DataTypes.DATEONLY },
	expiry_date: { type: DataTypes.DATEONLY },
	thematic_area_id: { type: DataTypes.INTEGER, allowNull: true },
	access_scope: { type: DataTypes.STRING, defaultValue: 'all' },
	status: { type: DataTypes.STRING, defaultValue: 'pending' },
	processing_status: { type: DataTypes.STRING, defaultValue: 'pending' },
	processing_error: { type: DataTypes.TEXT },
	file_id: { type: DataTypes.INTEGER },
	uploaded_by: { type: DataTypes.INTEGER },
	approved_by: { type: DataTypes.INTEGER },
	approved_at: { type: DataTypes.DATE },
	created_at: { type: DataTypes.DATE },
	updated_at: { type: DataTypes.DATE },
}, {
	tableName: 'ai_documents',
	timestamps: true,
	createdAt: 'created_at',
	updatedAt: 'updated_at',
});
